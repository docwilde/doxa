#!/usr/bin/env python3
"""Generate GitHub-renderable one-scene gallery pages and the README frame."""

from __future__ import annotations

from pathlib import Path
import re

from gallery_capture import load_gallery

ROOT = Path(__file__).resolve().parents[1]
SCENE_DIR = ROOT / "docs/gallery/scenes"
README = ROOT / "README.md"
START = "<!-- gallery-carousel:start -->"
END = "<!-- gallery-carousel:end -->"
PAGES_URL = "https://docwilde.github.io/doxa/gallery/"
GENERATED = "<!-- Generated by scripts/generate_gallery_pages.py from scenes.json. -->"


def read_scenes() -> tuple[str, list[dict[str, str]]]:
    manifest, _, _ = load_gallery(ROOT)
    return manifest["default"], manifest["scenes"]


def markdown_page(scenes: list[dict[str, str]], index: int) -> str:
    scene = scenes[index]
    previous = scenes[(index - 1) % len(scenes)]
    following = scenes[(index + 1) % len(scenes)]
    asset = Path(scene["image"]).name
    image = f"../../../assets/shots/{asset}"
    nav = (
        f"[← {previous['title']}](./{previous['id']}.md)"
        f" · [Next: {following['title']} →](./{following['id']}.md)"
    )
    return (
        f"{GENERATED}\n"
        f"# {scene['title']}\n\n"
        f"{nav}\n\n"
        f"**Scene {index + 1} of {len(scenes)}**\n\n"
        f"{scene['caption']}\n\n"
        f"[![{scene['alt']}]({image})]({image})\n\n"
        f"[Open the interactive gallery]({PAGES_URL}#{scene['id']}) · "
        f"[Back to the README gallery](../../../README.md#gallery)\n"
    )


def readme_frame(scenes: list[dict[str, str]], index: int) -> str:
    scene = scenes[index]
    previous = scenes[(index - 1) % len(scenes)]
    following = scenes[(index + 1) % len(scenes)]
    image = f"assets/shots/{Path(scene['image']).name}"
    return (
        f"**{scene['title']}** — {scene['caption']}\n\n"
        f"[![{scene['alt']}]({image})]({image})\n\n"
        f"[← {previous['title']}](docs/gallery/scenes/{previous['id']}.md)"
        f" · [Next: {following['title']} →](docs/gallery/scenes/{following['id']}.md)"
    )


def main() -> None:
    default, scenes = read_scenes()
    SCENE_DIR.mkdir(parents=True, exist_ok=True)
    retained = {f"{scene['id']}.md" for scene in scenes}
    for old_page in SCENE_DIR.glob("*.md"):
        if old_page.name not in retained and old_page.read_text(encoding="utf-8").startswith(GENERATED):
            old_page.unlink()
    for index, scene in enumerate(scenes):
        (SCENE_DIR / f"{scene['id']}.md").write_text(markdown_page(scenes, index), encoding="utf-8")

    readme = README.read_text(encoding="utf-8")
    if readme.count(START) != 1 or readme.count(END) != 1:
        raise SystemExit("README must contain exactly one generated gallery marker pair")
    block = f"{START}\n{readme_frame(scenes, next(i for i, scene in enumerate(scenes) if scene['id'] == default))}\n{END}"
    readme = re.sub(f"{re.escape(START)}.*?{re.escape(END)}", lambda _: block, readme, count=1, flags=re.S)
    README.write_text(readme, encoding="utf-8")


if __name__ == "__main__":
    main()
